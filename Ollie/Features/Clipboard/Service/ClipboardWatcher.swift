import AppKit
import Observation

@MainActor
@Observable
final class ClipboardWatcher {
    private(set) var isPaused = false
    private(set) var captureError: String?
    private let store: ClipboardStore
    @ObservationIgnored private var polling: Task<Void, Never>?
    @ObservationIgnored private var processing: Task<Void, Never>?
    @ObservationIgnored private var pending: [ClipboardCapture] = []
    @ObservationIgnored private var observer: NotificationToken?
    private var tracker = PasteboardChangeTracker(currentChangeCount: 0)
    private var signature: ClipboardContentSignature?

    init(store: ClipboardStore) {
        self.store = store
        let center = NotificationCenter.default
        observer = NotificationToken(center.addObserver(forName: .bufferDidWritePasteboard, object: nil, queue: .main) { [weak self] note in
            guard let count = (note.object as? NSNumber)?.intValue else { return }
            Task { @MainActor [weak self] in self?.tracker.recordSelfWrite(changeCount: count) }
        }, center: center)
    }

    func startWatching() {
        guard polling == nil else { return }
        tracker.reset(changeCount: NSPasteboard.general.changeCount)
        polling = Task { [weak self] in
            while !Task.isCancelled {
                do { try await Task.sleep(for: .milliseconds(500)) } catch { return }
                guard !Task.isCancelled else { return }
                self?.capture()
            }
        }
    }

    func stopWatching() {
        polling?.cancel()
        polling = nil
    }

    func finishPendingProcessing() async { await processing?.value }
    func pause() { isPaused = true }
    func resume() {
        tracker.reset(changeCount: NSPasteboard.general.changeCount)
        isPaused = false
    }

    private func capture() {
        guard !isPaused, pending.count < 8 else { return }
        let pasteboard = NSPasteboard.general
        guard tracker.shouldCapture(changeCount: pasteboard.changeCount) else { return }
        let concealed = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !concealed.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        let payload: ClipboardPayload
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            payload = .text(text)
        } else if let data = pasteboard.data(forType: .png) {
            payload = .image(.png(data))
        } else if let data = pasteboard.data(forType: .tiff) {
            payload = .image(.tiff(data))
        } else { return }
        let app = NSWorkspace.shared.frontmostApplication
        pending.append(ClipboardCapture(payload: payload, sourceApp: app?.localizedName, sourceBundleIdentifier: app?.bundleIdentifier))
        guard processing == nil else { return }
        processing = Task { [weak self] in
            guard let self else { return }
            defer { processing = nil }
            while !pending.isEmpty {
                let capture = pending.removeFirst()
                let previous = signature
                let result = await Task.detached(priority: .utility) { [storage = store.storage] in
                    Result { try Self.process(capture, previous: previous, storage: storage) }
                }.value
                switch result {
                case .success(let captured):
                    captureError = nil
                    if let (item, signature) = captured { self.signature = signature; store.add(item) }
                case .failure:
                    captureError = "A copied item could not be saved. Check available disk space."
                }
            }
        }
    }

    nonisolated static func process(
        _ capture: ClipboardCapture, previous: ClipboardContentSignature?, storage: ClipboardStorage
    ) throws -> (ClipboardItem, ClipboardContentSignature)? {
        switch capture.payload {
        case .text(let text):
            let data = Data(text.utf8)
            let signature = ClipboardContentSignature.text(utf8Data: data)
            guard signature != previous else { return nil }
            let item: ClipboardItem
            if data.count <= 10_000 {
                item = .text(text, timestamp: Date(), sourceApp: capture.sourceApp, sourceBundleIdentifier: capture.sourceBundleIdentifier)
            } else {
                guard let filename = storage.saveText(data) else { throw ClipboardContentError.unavailable }
                item = .largeText(preview: String(text.prefix(500)), timestamp: Date(), filename: filename, originalSizeBytes: data.count,
                    sourceApp: capture.sourceApp, sourceBundleIdentifier: capture.sourceBundleIdentifier)
            }
            return (item, signature)
        case .image(let image):
            let png: Data
            switch image {
            case .png(let data): png = data
            case .tiff(let data):
                guard let bitmap = NSBitmapImageRep(data: data), let converted = bitmap.representation(using: .png, properties: [:]) else { return nil }
                png = converted
            }
            let signature = ClipboardContentSignature.image(pngData: png)
            guard signature != previous else { return nil }
            guard let filename = storage.saveImage(png) else { throw ClipboardContentError.unavailable }
            return (.image(filename: filename, timestamp: Date(), sourceApp: capture.sourceApp, sourceBundleIdentifier: capture.sourceBundleIdentifier), signature)
        }
    }
}
